DEFAULT_HEADERS: dict[str, str] = {
    "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
    "Accept-Language": "en-US,en;q=0.9",
    "Accept-Encoding": "gzip, deflate",
    "Connection": "keep-alive",
}


def random_user_agent() -> str:
    """Return a random User-Agent from the curated pool."""
    import random
    return random.choice(USER_AGENTS)


def get_session(args: argparse.Namespace) -> requests.Session:
    """Create a shared requests.Session with realistic headers and retries."""
    session = requests.Session()
    session.headers.update(DEFAULT_HEADERS)
    session.headers["User-Agent"] = random_user_agent()
    adapter = HTTPAdapter(max_retries=1)
    session.mount("https://", adapter)
    session.mount("http://", adapter)
    return session


def safe_get(session: requests.Session, url: str, **kwargs) -> requests.Response | None:
    """GET a URL, rotating UA and catching all requests exceptions."""
    session.headers["User-Agent"] = random_user_agent()
    try:
        return session.get(url, **kwargs)
    except requests.RequestException:
        return None
